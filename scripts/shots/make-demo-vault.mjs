// Builds an invented vault for screenshots of tasks-desktop: a colorscheme plugin "lumen.nvim", its
// palette editor "lumen-desktop" and their docs. Nothing in it comes from a real vault.
//
//   node make-demo-vault.mjs <target folder>     (the folder is replaced)
//
// Needs nvim and a checkout of tasks.nvim (REPOS_DIR/tasks.nvim, or TASKS_ENGINE_DIR). No shell is
// involved: on Windows `bash` may be the one of WSL, which does not take the paths of this side.
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const vault = process.argv[2];
if (!vault) throw new Error('target folder');
const repos = process.env.REPOS_DIR;
if (!process.env.TASKS_ENGINE_DIR && !repos) throw new Error('REPOS_DIR is not set');
const script = join(
  process.env.TASKS_ENGINE_DIR ?? join(repos ?? '', 'tasks.nvim'),
  'scripts',
  'tasks.lua',
);
if (!existsSync(script)) throw new Error(`no tasks.nvim checkout: ${script} is missing`);

// Nothing of this machine's own vault: with TASKS_MARKER_DOCS set, finishing a task here would
// refresh a document of the real vault.
const env = { ...process.env };
for (const key of Object.keys(env)) if (key.startsWith('TASKS_')) delete env[key];

/** One call of the tasks CLI; returns what it printed. */
const tasks = (...args) =>
  execFileSync('nvim', ['-n', '-i', 'NONE', '--headless', '-u', 'NONE', '-l', script, ...args], {
    env,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  });
const t = (...args) => tasks(`--vault=${vault}`, ...args);

rmSync(vault, { recursive: true, force: true });
tasks('init-vault', vault, '--area=lumen.nvim', '--lang=en', '--apply');
rmSync(join(vault, 'lumen.nvim', 'ROADMAP', 'tasks', 'first-task-create-edit-finish.md'), {
  force: true,
});
t('bootstrap', 'lumen-desktop', '--lang=en', '--apply');
t('bootstrap', 'docs', '--lang=en', '--apply');

